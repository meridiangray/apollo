"""genicons.py — writes apollo/go/ui/entity-icons.js from hydra's SCHEMA_ICON.

Run with hydra's interpreter:  ~/.venvs/hydra/bin/python apollo/py/genicons.py
Each schema of hydra's composed schema takes its own icon or the nearest ancestor's (hydra.wiki.look.icons.token);
the shipped SVGs (template/.hydra/resources/icons/) are inlined, so the page needs no icon requests."""
import json
import re
from pathlib import Path

from hydra.archive import layout, resources
from hydra.machine import iconlib
from hydra.schema import loader as hschema
from hydra.wiki.look import icons

OUT = Path(__file__).resolve().parent.parent / "go" / "ui" / "entity-icons.js"
SHIPPED = resources.TEMPLATE / layout.RESOURCES_DIR / "icons"
HEADER = """/* Entity-type icons: Hydra's default schema -> icon mapping (hydra.wiki.look.icons.SCHEMA_ICON, resolved down each
   schema's extends chain), generated by apollo/py/genicons.py from Hydra's shipped icon set; do not edit by hand.
   Tabler Icons, MIT licence (https://github.com/tabler/tabler-icons); the user/users/circle-dashed and other plain-named
   marks are Lucide, ISC licence. The engine-run decision kinds (the lower-case keys: merge, tie, ask ...) are Tabler too,
   from the local 3.52.0 set (genicons.DECISION_ICON). No game-icons are used. Anything without an icon of its own takes _default. */
"""

# every decision kind the engine flows write (pageflow/flows/*.py, decisions.jsonl "kind"), keyed as it appears -> a Tabler icon
DECISION_ICON = {
    "prop": "list-details", "accept": "circle-check", "reject": "circle-x", "leave": "player-pause", "order": "arrows-sort",
    "ask": "help-circle", "answer": "message-check", "bind": "map-pin-check", "tie": "link-plus", "verdict": "gavel",
    "merge": "arrow-merge", "date": "calendar-event", "link": "link", "none": "circle-off", "alias": "tags",
    "apart": "arrows-split", "stake": "chart-pie", "rename": "cursor-text", "retype": "replace", "resolve": "scale",
    "change": "arrows-exchange", "end": "calendar-off", "payment": "cash", "point": "map-pin", "transfer": "arrow-bar-right",
    "stub": "file-plus", "collection": "folders", "group": "category-2", "country": "world", "role": "id-badge",
    "same-name": "copy", "place-fit": "target", "item": "bookmark-plus", "unknown": "question-mark", "extension": "puzzle",
    "drop": "trash-x",
}


def inline(token: str) -> str:
    text = (SHIPPED / f"{icons.FILE.get(token, token)}.svg").read_text(encoding="utf-8")
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    text, n = re.subn(r'class="[^"]*"', 'class="ico" aria-hidden="true"', text, count=1)
    if not n:
        text = text.replace("<svg", '<svg class="ico" aria-hidden="true"', 1)
    return re.sub(r"\s*\n\s*", " ", text).strip()


def inline_tabler(name: str) -> str:
    f = iconlib.path(f"tabler:{name}")
    if f is None:
        raise SystemExit(f"tabler icon {name} is not in the local iconlib (fetch it first)")
    text = re.sub(r"<!--.*?-->", "", f.read_text(encoding="utf-8"), flags=re.S)
    text = re.sub(r'\s*<path stroke="none" d="M0 0h24v24H0z" fill="none" />', "", text)
    text = re.sub(r'class="[^"]*"', 'class="ico" aria-hidden="true"', text, count=1)
    return re.sub(r"\s*\n\s*", " ", text).strip()


def main() -> None:
    hschema.load()
    names = sorted(set(hschema.SCHEMA) | set(icons.SCHEMA_ICON))
    rows = {n: icons.token(n) for n in names}
    rows = {n: t for n, t in rows.items() if t and n != "Thing"}
    body = {n: inline(t) for n, t in rows.items()}
    assert len(set(DECISION_ICON.values())) == len(DECISION_ICON), "two decision kinds share an icon"
    body.update({k: inline_tabler(v) for k, v in DECISION_ICON.items()})
    body["_default"] = inline(icons.PLACEHOLDER)
    lines = [f"  {json.dumps(k)}: {json.dumps(v)}" for k, v in body.items()]
    OUT.write_text(HEADER + "window.ENTITY_ICONS = {\n" + ",\n".join(lines) + "\n};\n", encoding="utf-8")
    print(f"{len(rows)} schemas -> {OUT}")


if __name__ == "__main__":
    main()
